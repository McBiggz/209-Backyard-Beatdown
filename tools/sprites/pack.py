# Packs every wrestler's sprite sheet (assets/sprites/<id>.webp, one 320x224 box per frame) into a tight atlas
# (assets/sprites_packed/<id>.webp) and writes src/03b_pack.js with where each frame sits.
# The game draws straight from the atlas instead of unpacking ~1,600 separate canvases (about 430 MB) at load.
# Run this after any sprite builder, then `node build.mjs` (the build stops if an atlas is out of date).
import json, re, hashlib, os
import numpy as np
from PIL import Image
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
R = os.path.abspath(R)
js = open(f'{R}/src/03_assets.js').read()
os.makedirs(f'{R}/assets/sprites_packed', exist_ok=True)
W, CW, CH, PAD = 1024, 320, 224, 1
out = {}
for m in re.finditer(r'"(\w+)": \{"src": "SPR\(sprites/(\w+)\.webp\)", "names": (\[[^\]]*\]), "cols": (\d+)\}', js):
    wid, names, cols = m.group(1), json.loads(m.group(3)), int(m.group(4))
    path = f'{R}/assets/sprites/{wid}.webp'
    sheet = Image.open(path).convert('RGBA')
    cells = []
    for i, n in enumerate(names):
        c = sheet.crop(((i % cols) * CW, (i // cols) * CH, (i % cols) * CW + CW, (i // cols) * CH + CH))
        a = np.asarray(c)[..., 3] > 0
        if not a.any():
            cells.append((n, None, 0, 0)); continue
        ys, xs = np.nonzero(a.any(1))[0], np.nonzero(a.any(0))[0]
        x0, y0, x1, y1 = xs[0], ys[0], xs[-1] + 1, ys[-1] + 1
        cells.append((n, c.crop((x0, y0, x1, y1)), int(x0), int(y0)))
    # shelf packing, tallest first
    order = sorted([c for c in cells if c[1] is not None], key=lambda c: -c[1].size[1])
    x = y = shelf = 0; place = {}
    for n, im, ox, oy in order:
        w, h = im.size
        if x + w > W: x, y, shelf = 0, y + shelf + PAD, 0
        place[n] = (x, y, w, h, ox, oy); x += w + PAD; shelf = max(shelf, h)
    H = y + shelf
    atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    for n, im, ox, oy in order:
        atlas.paste(im, place[n][:2])
    atlas.save(f'{R}/assets/sprites_packed/{wid}.webp', lossless=True, method=6, quality=100)
    out[wid] = {'src': f'__ASSET(sprites_packed/{wid}.webp)__', 'h': hashlib.sha1(open(path, 'rb').read()).hexdigest()[:12],
                'f': {n: list(place[n]) for n in names if n in place}}
    print(f'{wid:10} {len(names)} frames  {sheet.size[0]}x{sheet.size[1]} -> {W}x{H}')
open(f'{R}/src/03b_pack.js', 'w').write('// GENERATED by tools/sprites/pack.py - do not edit\nconst PACK=' + json.dumps(out, separators=(',', ':')) + ';\n')
